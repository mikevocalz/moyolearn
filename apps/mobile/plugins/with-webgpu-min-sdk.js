/**
 * Raises the Android `minSdkVersion` to 26, which `react-native-webgpu` needs.
 *
 * WHY THIS FILE EXISTS RATHER THAN A LINE IN `gradle.properties`. Dawn's Android
 * surface path calls `AHardwareBuffer_allocate` / `_lock` / `_describe` /
 * `_acquire` / `_release` (react-native-webgpu/android/cpp/
 * AndroidPlatformContext.h), and every one of those was introduced in API 26.
 * At Expo's default minSdk of 24 the NDK does not merely warn — it refuses:
 *
 *   error: 'AHardwareBuffer_allocate' is unavailable: introduced in Android 26
 *
 * so `:react-native-webgpu:buildCMakeRelWithDebInfo[arm64-v8a]` fails and there
 * is no binary at all. This is not a warning to suppress: guarding the calls
 * away would leave a library that links on API 24 and crashes the first time a
 * child opened the tutor on such a device.
 *
 * The setting has to live in a config plugin because `android/gradle.properties`
 * is REGENERATED by `expo prebuild` — verified, not assumed: a prebuild run on
 * this project reproduced that file byte-for-byte. A hand-edit there survives
 * until the next prebuild and then vanishes, and the failure it comes back as
 * (a C++ availability error inside node_modules) looks nothing like its cause.
 *
 * `android.minSdkVersion` is the gradle property Expo's autolinking settings
 * plugin maps onto the `minSdk` version-catalog entry
 * (ExpoAutolinkingSettingsExtension.kt), which `expo-root-project` then reads
 * with `setIfNotExist` — so setting the property wins over the default without
 * patching any generated Gradle file.
 *
 * COST: Android 8.0 (2017) becomes the floor, up from 7.0. That is a real
 * product decision and it is recorded in ADR-111 rather than only here.
 *
 * SOT: docs/decisions/adr-111-native-3d-runtime.md
 * SOT-KEYWORDS: minsdk android webgpu dawn ahardwarebuffer config-plugin prebuild api26
 */
const { withGradleProperties } = require('@expo/config-plugins');

const MIN_SDK_FOR_WEBGPU = '26';

module.exports = function withWebGpuMinSdk(config) {
  return withGradleProperties(config, (gradleConfig) => {
    const properties = gradleConfig.modResults;
    const existing = properties.find(
      (item) => item.type === 'property' && item.key === 'android.minSdkVersion',
    );
    if (existing) {
      // Only ever raise. A project that has already declared a higher floor for
      // some other reason must keep it — this plugin's job is a minimum, not a
      // pin, and silently lowering someone else's floor would be a regression
      // with no visible cause.
      if (Number(existing.value) < Number(MIN_SDK_FOR_WEBGPU)) {
        existing.value = MIN_SDK_FOR_WEBGPU;
      }
      return gradleConfig;
    }
    properties.push({
      type: 'property',
      key: 'android.minSdkVersion',
      value: MIN_SDK_FOR_WEBGPU,
    });
    return gradleConfig;
  });
};
