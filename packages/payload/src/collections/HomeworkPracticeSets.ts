import type { CollectionConfig } from 'payload';

// A guardian-reviewed practice set generated from one submission's gaps.
//
// GUARDIAN-SCOPED, and that is the whole access story: `guardianAuthId` is set
// from `ctx` when the draft is saved, and every read and the approve write in
// `apps/web/lib/homework.repository.ts` carry `guardianAuthId = ctx.learnerId`.
// `items[].answer` is the answer key, which the design doc keeps guardian-only;
// a learner session names a practice set id and gets nothing, not a 403, so the
// id space is not an oracle over which children have sets.
//
// `items` is JSON for the `tutorSessions.messages` reason: the set is written
// once by the generator and read whole by the print route, and every item was
// verified by `checkExactMath` before it was saved (contract §Practice sets).
// `seed` is stored so the sheet can be regenerated byte-for-byte for the key.
//
// No `expiresAt`: a practice set is the guardian's artefact and goes with the
// account cascade, like the submission it was built from.
// SOT: docs/design/homework-end-to-end-2026.md · docs/work/pr-100/contract.md §Data §Practice sets · docs/decisions/adr-124-homework-submissions-persistence.md
// SOT-KEYWORDS: homework practice set guardian approve draft answer key seed targeted tags items verified checker

export const HomeworkPracticeSets: CollectionConfig = {
  slug: 'homeworkPracticeSets',
  // VERSIONS OFF — the canary defaults them ON (see Leads.ts); a shadow copy
  // of an answer key is a second place the key lives, swept by nothing.
  versions: false,
  admin: {
    useAsTitle: 'practiceSetId',
    defaultColumns: ['practiceSetId', 'learnerAuthId', 'guardianAuthId', 'status'],
  },
  access: {
    read: ({ req }) => Boolean(req.user),
    update: ({ req }) => Boolean(req.user),
  },
  fields: [
    { name: 'practiceSetId', type: 'text', required: true, unique: true, index: true },
    // Pointer to `homeworkSubmissions.submissionId`, never a relationship.
    { name: 'submissionId', type: 'text', required: true, index: true },
    { name: 'learnerAuthId', type: 'text', required: true, index: true },
    // The guardian who drafted and may approve. Both this and `learnerAuthId`
    // are in `SUBJECT_COLLECTIONS`: the set is erased when either account goes.
    { name: 'guardianAuthId', type: 'text', required: true, index: true },
    {
      name: 'status',
      type: 'select',
      required: true,
      defaultValue: 'draft',
      index: true,
      options: ['draft', 'approved'],
    },
    { name: 'seed', type: 'text', required: true },
    // `string[]` of skill tags the generator targeted.
    { name: 'targetedTags', type: 'json', required: true, defaultValue: [] },
    // `PracticeItem[]`. Each `answer` was checked before the row was written.
    { name: 'items', type: 'json', required: true, defaultValue: [] },
  ],
};
